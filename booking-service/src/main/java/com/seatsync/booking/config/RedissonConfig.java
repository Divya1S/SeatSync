package com.seatsync.booking.config;

import org.redisson.Redisson;
import org.redisson.api.RedissonClient;
import org.redisson.config.Config;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Plain Redisson client (no starter), configured from the same
 * SPRING_DATA_REDIS_HOST / SPRING_DATA_REDIS_PORT backed properties
 * as the Spring Data Redis connection. Used only for the inventory
 * seeding lock ({@code lock:inventory:{eventId}}).
 */
@Configuration
public class RedissonConfig {

    @Bean(destroyMethod = "shutdown")
    public RedissonClient redissonClient(@Value("${spring.data.redis.host}") String host,
                                         @Value("${spring.data.redis.port}") int port) {
        Config config = new Config();
        config.useSingleServer().setAddress("redis://" + host + ":" + port);
        return Redisson.create(config);
    }
}
